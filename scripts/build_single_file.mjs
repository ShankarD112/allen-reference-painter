import { readFile, writeFile } from "node:fs/promises";
let html = await readFile("dist/index.html", "utf8");
const script = html.match(/<script[^>]+src="([^"]+)"[^>]*><\/script>/),
  style = html.match(/<link[^>]+href="([^"]+\.css)"[^>]*>/);
if (!script || !style)
  throw Error("Expected one application bundle and stylesheet.");
const js = await readFile("dist/" + script[1].replace(/^\.\//, ""), "utf8"),
  css = await readFile("dist/" + style[1].replace(/^\.\//, ""), "utf8"),
  runtime = await readFile("public/share/viewer.js", "utf8");
html = html
  .replace(script[0], "")
  .replace(style[0], () => "<style>" + css + "</style>");
html = html.replace(
  "</body>",
  () =>
    "<script>globalThis.PAINTER_SHARE_RUNTIME=" +
    JSON.stringify(runtime).replaceAll("<", "\\u003c") +
    ';</script><script type="module">' +
    js.replace(/<\/script/gi, "<\\/script") +
    "</script></body>",
);
html =
  "<!-- Complete Reference Painter application code. Serve over HTTP(S) beside the data/ atlas directory generated by npm run build. No separate JavaScript or CSS files required. Atlas binaries remain external scientific data. -->\n" +
  html;
await writeFile("dist/reference-painter.html", html);
console.log(
  "Built dist/reference-painter.html: complete app code with embedded styles and offline export runtime.",
);
